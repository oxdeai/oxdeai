import { repositoryMetadata } from "../../packages/conformance/src/evidenceScope.mjs";
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { AUTHORITY, SECONDARY, ROOT, project, serialize, verifyEquivalent, check, MODES } from './profile-c.mjs';
import { MANIFEST, verifyAuthority } from './verify-authority.mjs';
const source = JSON.parse(readFileSync(resolve(ROOT, AUTHORITY), 'utf8'));
const metadata = JSON.parse(readFileSync(resolve(ROOT, MANIFEST), 'utf8'));

test('committed projection is byte-exact, deterministic and read-only', () => {
  const before = readFileSync(resolve(ROOT, SECONDARY));
  check();check();
  assert.equal(serialize(project(source)), serialize(project(source)));
  assert.deepEqual(readFileSync(resolve(ROOT, SECONDARY)), before);
});
test('all modes explicitly map outcome/status/reason and preserve every other field', () => {
  const secondary = project(source);
  assert.deepEqual(secondary.vectors.map(v => v.id), source.vectors.map(v => v.id));
  for (const [i,v] of source.vectors.entries()) {
    const [status,reason] = MODES[v.mode];
    assert.deepEqual(secondary.vectors[i].expected, reason ? {status,reason} : {status});
    const {expected: ignored, ...fields} = secondary.vectors[i];
    const {expected: original, ...originalFields} = v;
    assert.deepEqual(fields, originalFields);
  }
  verifyEquivalent(source, secondary);
});
test('key insertion order is irrelevant to generation; vector order is preserved', () => {
  const reversed = Object.fromEntries(Object.entries(source).reverse());
  assert.equal(serialize(project(reversed)), serialize(project(source)));
  reversed.vectors = [...source.vectors].reverse();
  assert.deepEqual(project(reversed).vectors.map(v=>v.id), reversed.vectors.map(v=>v.id));
});
