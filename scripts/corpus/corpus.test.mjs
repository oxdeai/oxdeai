test('format-only drift fails exact-byte CI check without changing any file', () => {
  const root=mkdtempSync(resolve(tmpdir(),'oxdeai-projection-'));
  try {
    for (const path of [AUTHORITY,SECONDARY]) {
      mkdirSync(dirname(resolve(root,path)),{recursive:true});
      writeFileSync(resolve(root,path),readFileSync(resolve(ROOT,path)));
    }
    check(root);
    const changed=JSON.stringify(project(source));
    writeFileSync(resolve(root,SECONDARY),changed);
    assert.throws(()=>check(root),/generated bytes drift/);
    assert.equal(readFileSync(resolve(root,SECONDARY),'utf8'),changed);
  } finally {rmSync(root,{recursive:true,force:true});}
});
